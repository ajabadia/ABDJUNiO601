// ROM 0B30_LfoDelayRampTbl — master ROM (ic37) at 0x0B30, 8 x uint16 little-endian.
// Index = delay pot byte >> 4. Index 0 is 0xFFFF: the delay ramp completes in one
// tick, i.e. "delay off".
const uint16_t kDefaultLfoRampTbl[kLfoRampTableSize] = {
    0xFFFF, 0x0419, 0x020C, 0x015E, 0x0100, 0x0100, 0x0100, 0x0100};

uint16_t getLfoSpeedCoeff(int index) noexcept
{
    const int i = std::clamp(index, 0, kLfoSpeedTableSize - 1);
    return kDefaultLfoSpeedTbl[i];
}

uint16_t getLfoRampIncrement(int index) noexcept
{
    const int i = std::clamp(index, 0, kLfoRampTableSize - 1);
    return kDefaultLfoRampTbl[i];
}

